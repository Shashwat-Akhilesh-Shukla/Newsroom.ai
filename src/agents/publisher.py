# Publisher Agent - Final gatekeeper and publishing
#
# This agent will:
# - Perform final pre-publication checks:
#   - SEO optimization (meta tags, keywords, descriptions)
#   - Duplicate content detection
#   - Platform-specific formatting (Medium, blog, etc.)
#   - Image and media validation
#   - Link checking
#   - Reading time estimation
#
# - Validate publishing requirements:
#   - All required fields present
#   - Proper categorization and tagging
#   - Legal and compliance checks
#   - Brand guidelines adherence
#
# - Make final routing decisions:
#   - If any check fails: send back to Editor with specific issues
#   - If all checks pass: proceed to publish
#
# - Handle publishing logistics:
#   - Schedule publication time
#   - Format for target platform
#   - Generate social media snippets
#   - Create distribution plan
#
# - Archive published content and metadata
# - Track publication metrics and performance
