# Research Agent - Deep research and citation gathering
#
# This agent will:
# - Conduct comprehensive research on the topic from Scout
# - Gather information from multiple sources:
#   - Academic papers (ArXiv, Google Scholar)
#   - Technical blog posts
#   - GitHub repositories and READMEs
#   - Official documentation
#   - News articles
#
# - Extract and structure key information:
#   - Main claims with supporting evidence
#   - Citations and references
#   - Technical details and specifications
#   - Open questions and unknowns
#   - Conflicting viewpoints
#
# - Organize research notes in a structured format
# - Does NOT make relevance judgments (that's Skeptic's job)
# - Pass all findings to Skeptic agent for validation
# - Can be called back by Editor for fact-checking specific claims
